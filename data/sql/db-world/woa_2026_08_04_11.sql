-- comparison is direct.
--
-- Single-column UPDATE, not DELETE + full-row INSERT: a re-INSERT would revert
-- woa_2026_08_04_09.sql (Stances) and woa_2026_08_04_10.sql (damage retune).
--
-- Blizzard's own 50589 stays untouched.
--
-- ===========================================================================

